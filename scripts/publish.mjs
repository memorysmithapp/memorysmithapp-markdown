#!/usr/bin/env node
// Decides, and then does, what the release workflow publishes to npm once `scripts/release.mjs`
// has decided what it releases, so that nobody publishes by hand after a package's first time:
//
//   1. on any push that is not a release (`skip`), nothing is published;
//   2. every package of the workspace not marked private is published at the version of the tag,
//      and a package whose version is not the tag's fails the run;
//   3. on a release (`release`), a version that already exists on npm fails the run: the tag was
//      written just now, so the version on npm is somebody else's, or a hand's;
//   4. on a run again of a release whose tag exists on this commit (`tagged`), the packages already
//      on npm at that version are left as they are and the rest are published, which is how a run
//      that failed halfway is finished;
//   5. a package npm has never seen is left for the owner: a trusted publisher is configured on a
//      package that exists, so its first publish is made by hand, once (SDLC.md §10).
//
// Each package is packed by pnpm, which writes `workspace:` ranges as versions, and the tarball is
// published by npm through trusted publishing: no token, and provenance generated by npm.
//   node scripts/publish.mjs <action> <tag> [--dry-run]
//
// `--dry-run` decides, packs and asks npm for a dry run of each publish, and sends nothing.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { workspacePackages } from './quality.mjs';

export function planPublish({ action, tag, packages, published, exists = () => true }) {
  if (action !== 'release' && action !== 'tagged') {
    return { action: 'skip', publish: [], reason: `the release workflow decided "${action}": this push publishes nothing` };
  }
  const version = tag.replace(/^v/, '');
  const publish = [];
  const kept = [];
  const first = [];
  for (const pkg of packages) {
    if (pkg.version !== version) {
      return { action: 'fail', publish: [], reason: `${pkg.name} is at ${pkg.version}, not at ${version}, the version of ${tag}` };
    }
    if (!exists(pkg.name)) {
      first.push(pkg.name);
      continue;
    }
    if (published(pkg.name, version)) {
      if (action === 'release') {
        return { action: 'fail', publish: [], reason: `${pkg.name}@${version} already exists on npm, and ${tag} was written just now: a version is published once` };
      }
      kept.push(pkg.name);
      continue;
    }
    publish.push(pkg);
  }
  const notes = [
    publish.length ? `publishing ${publish.map((pkg) => `${pkg.name}@${version}`).join(', ')}` : '',
    kept.length ? `${kept.join(', ')} already on npm at ${version}` : '',
    first.length ? `${first.join(', ')} not on npm yet: the first publish is the owner's (SDLC.md §10)` : '',
  ].filter(Boolean);
  return { action: publish.length === 0 ? 'skip' : 'publish', publish, first, reason: notes.join('; ') || 'nothing to publish' };
}

/** What npm answers about a package, or `null` when it has never seen it. */
function npmView(spec) {
  try {
    return execFileSync('npm', ['view', spec, 'version', '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  } catch (error) {
    if (/E404|404 Not Found/.test(`${error.stdout ?? ''}${error.stderr ?? ''}`)) return null;
    throw error;
  }
}

/** Whether npm has this version of the package. */
const onNpm = (name, version) => Boolean(npmView(`${name}@${version}`));

/** Whether npm has the package at all. */
const knownToNpm = (name) => npmView(name) !== null;

/** The packages of the workspace that are published: every one not marked private. */
export function publishedPackages(root) {
  return workspacePackages(root)
    .map((dir) => ({ dir, ...JSON.parse(readFileSync(join(root, dir, 'package.json'), 'utf8')) }))
    .filter((pkg) => pkg.private !== true)
    .map(({ dir, name, version }) => ({ dir, name, version }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [action, tag] = process.argv.slice(2).filter((arg) => !arg.startsWith('--'));
  const dryRun = process.argv.includes('--dry-run');
  if (!action || !tag) {
    console.error('usage: node scripts/publish.mjs <action> <tag>');
    process.exit(2);
  }
  const root = resolve('.');
  const result = planPublish({ action, tag, packages: publishedPackages(root), published: onNpm, exists: knownToNpm });
  console.error(result.reason);
  if (result.action === 'fail') process.exit(1);
  for (const pkg of result.publish) {
    const out = mkdtempSync(join(tmpdir(), 'publish-'));
    try {
      execFileSync('pnpm', ['pack', '--pack-destination', out], { cwd: join(root, pkg.dir), stdio: 'inherit' });
      const tarball = readdirSync(out).find((name) => name.endsWith('.tgz'));
      if (!tarball || !existsSync(join(out, tarball))) throw new Error(`pnpm pack wrote no tarball for ${pkg.name}`);
      execFileSync('npm', ['publish', join(out, tarball), '--access', 'public', ...(dryRun ? ['--dry-run'] : [])], { stdio: 'inherit' });
    } finally {
      rmSync(out, { recursive: true, force: true });
    }
  }
}
